/**
 * Find one catalogue entry by its stable id, or null when unknown.
 *
 * @param string $id
 * @return array|null
 */
function get_provider_catalog_entry($id)
{
    foreach (get_provider_catalog() as $provider) {
        if ($provider['id'] === $id) {
            return $provider;
        }
    }

    return null;
}

