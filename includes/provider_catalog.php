/**
 * Cancellation data for one catalogue provider, or null when none is known.
 *
 * @param string|null $providerId
 * @return array{cancel_url: string, hosts: string[], url_patterns: string[], detectable: bool}|null
 */
function provider_catalog_cancel_info($providerId)
{
    $providerId = (string) $providerId;
    $rules = get_provider_cancellation_rules();
    if ($providerId === '' || !isset($rules[$providerId])) {
        return null;
    }

    $rule = $rules[$providerId];
    $hosts = array_values($rule['hosts'] ?? []);

    return [
        'cancel_url' => $rule['cancel_url'],
        'hosts' => $hosts,
        'url_patterns' => array_values($rule['url_patterns'] ?? []),
        'detectable' => $hosts !== [],
    ];
}

/**
 * Remote PNG URL for a catalogue logo slug (selfh.st icon set via jsDelivr).
 * Same source Diamon already uses in logo search — bundled at save time into
 * images/uploads/logos, not hotlinked on subscription cards.
 *
 * @param string $slug
 * @return string|null
 */
function provider_catalog_logo_remote_url($slug)
{
    $slug = preg_replace('/[^a-zA-Z0-9._-]/', '', $slug);
    if ($slug === '' || preg_match('/\.\.|^\.|^-/', $slug)) {
        return null;
    }

    return 'https://cdn.jsdelivr.net/gh/selfhst/icons/png/' . $slug . '.png';
}

/**
 * @param string $providerId
 * @return string|null
 */
function provider_catalog_logo_url_for_id($providerId)
{
    $entry = get_provider_catalog_entry($providerId);
    if ($entry === null || empty($entry['logo_slug'])) {
        return null;
    }
    if (array_key_exists('remote_logo', $entry) && $entry['remote_logo'] === false) {
        return null;
    }

    return provider_catalog_logo_remote_url($entry['logo_slug']);
}
